// 法规名显示层（纯函数，无依赖，可被 vitest 直接覆盖）
//
// 背景：库里的法规名最长 40 字——「最高人民法院关于适用《中华人民共和国涉外民事关系法律适用法》
// 若干问题的解释（二）」。而专题左栏只有 340px，法规名还得跟条号、↑↓✕ 按钮分地方：实测那行
// 只给得出 148px，全名要 480px，于是只能显示前 12 字——同一部法规的「解释（一）」和
// 「解释（二）」在列表里长得一模一样，根本分不出来。
//
// 这里只压套话、保留能区分的那一段。全名不丢：列表悬停可见，中栏顶部完整显示。

/** 发文机关前缀，连同其后的「关于」一起压掉 */
const AGENCY_RE =
  /^(?:最高人民法院|最高人民检察院|国务院|全国人民代表大会常务委员会|全国人民代表大会)(?:关于)?/

/** 紧跟在机关名后的「人民法院」（如「…关于人民法院民事执行中查封…的规定」），其后才是真正的主语 */
const COURT_RE = /^人民法院(?=民事|刑事|行政|执行)/

/** 套话：有没有都不影响辨识 */
const NOISE_RE = /若干问题(?:的)?|中华人民共和国/g

/** 起首的泛动词 */
const VERB_RE = /^(?:审理|印发|发布)/

/**
 * 法规显示简称：
 *   「最高人民法院关于适用《中华人民共和国民法典》物权编的解释（一）」→「民法典·物权编的解释（一）」
 *   「中华人民共和国民法典」→「民法典」
 *   「最高人民法院关于适用《中华人民共和国公司法》若干问题的规定（一）」→「公司法·规定（一）」
 *
 * 只做套话压缩，不猜测语义。压完为空或没变化时原样返回——宁可长，不可错。
 */
export function shortLawName(raw: string): string {
  const full = String(raw ?? '').trim()
  if (!full) return ''
  let s = full.replace(AGENCY_RE, '').replace(/^关于/, '')
  // 「适用《主体》后缀」：主体才是这部法规的本名，括号里的是它所解释的对象
  const nested = /^适用《(.+?)》(.*)$/.exec(s)
  if (nested) s = `${nested[1]}·${nested[2]}`
  s = s.replace(NOISE_RE, '').replace(COURT_RE, '').replace(VERB_RE, '')
  s = s.replace(/·{2,}/g, '·').replace(/^[·、，,\s]+|[·、，,\s]+$/g, '')
  return s || full
}
